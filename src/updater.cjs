class UpdateController {
  constructor({ updater, packaged, installed = true, platform, signedMac, release, onStatus = () => {} }) {
    this.updater = updater; this.onStatus = onStatus; this.enabled = true; this.pending = null;
    this.reason = !packaged ? 'Dasturchi rejimi' : !release.owner || !release.repo ? 'Yangilanish manzili sozlanmagan' : platform === 'darwin' && !signedMac ? 'Mac avtomatik yangilanishi Apple imzosi bilan chiqarilgan versiyada yoqiladi.' : !installed ? 'Avtomatik yangilanish uchun Setup orqali o‘rnating.' : '';
    this.state = { phase: this.reason ? 'unavailable' : 'idle', text: this.reason || 'Yangilanishlar avtomatik tekshiriladi.' };
    if(this.reason) return;
    // app-update.yml is generated by electron-builder from the fixed public repository.
    updater.autoDownload = true; updater.autoInstallOnAppQuit = true; updater.allowDowngrade = false; updater.allowPrerelease = false;
    updater.logger = null;
    updater.on('checking-for-update', () => this.set('checking','Yangilanish tekshirilmoqda…'));
    updater.on('update-not-available', () => this.set('current','Eng yangi versiya o‘rnatilgan.'));
    updater.on('update-available', info => this.set(this.enabled?'downloading':'available',`${info.version} ${this.enabled?'versiya yuklanmoqda…':'versiya mavjud. Yuklab olish tugmasidan foydalaning.'}`));
    updater.on('download-progress', info => this.set('downloading',`Yangilanish yuklanmoqda: ${Math.floor(info.percent)}%`));
    updater.on('update-downloaded', info => this.set('ready',`${info.version} tayyor. Dasturdan to‘liq chiqqanda o‘rnatiladi.`));
    updater.on('error', () => this.set('error','Yangilanishni olish imkoni bo‘lmadi. Keyinroq yana tekshiriladi.'));
  }
  set(phase,text) { this.state = {phase,text}; this.onStatus(this.state); }
  setEnabled(enabled) { this.enabled = enabled; if(!this.reason) { this.updater.autoDownload = enabled; this.updater.autoInstallOnAppQuit = enabled; } }
  async check(manual = false) {
    if(this.reason || (!this.enabled && !manual) || this.state.phase === 'ready') return this.state;
    if(this.pending) { await this.pending; return this.state; }
    this.pending = Promise.resolve().then(()=>this.updater.checkForUpdates()).catch(() => this.set('error','Yangilanish tekshirilmadi. Internetni tekshiring.'));
    try { await this.pending; } finally { this.pending = null; } return this.state;
  }
  install() { if(this.reason || this.state.phase !== 'ready') return false; this.updater.quitAndInstall(false,true); return true; }
}
module.exports = { UpdateController };
